export function furnitureName(id: string, language: Locale): string {
 const item=getCatalogItem(id);if(!item)return id;if(item.customized)return item.name;
 if(language==='pt')return portugueseFurnitureNames[id]??item.name;
 const match=/^csm_(shelves|hanging|drawers)_([1-6])_(open|doors)$/.exec(id);
 if(match&&language!=='fr'){const count=Number(match[2]);const label=language==='ar'?({shelves:count+' رفوف',hanging:'مساحة تعليق',drawers:count+' أدراج'}[match[1]]):({shelves:count+' shelves',hanging:'Hanging rail',drawers:count+' drawers'}[match[1]]);return label+(match[3]==='doors'?(language==='ar'?' مع أبواب':' with doors'):'');}
 if(language==='ar')return translateUi(language,frenchFurnitureNames[id]??item.name);
 return language==='fr'?frenchFurnitureNames[id]??item.name:translateUi(language,item.name);
}


/** User-authored model names are retained verbatim in every interface language. */
export function customModelName(item: FurnitureItem, project?: Project | null): string | undefined {
  return item.customModelId ? project?.customModels?.find(model => model.id === item.customModelId)?.name : undefined;
}
